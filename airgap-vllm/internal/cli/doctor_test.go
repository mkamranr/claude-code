// wellFormedToolCall is a fakevllm ChatCompletion fixture used by the Doctor
// end-to-end tests below: the smoke test must pass so the branch being tested
// (unreachable server, unserved model, context-window warnings) is the only
// thing that can make the test fail.
const wellFormedToolCall = `{"id":"c1","choices":[{"message":{"tool_calls":[
	{"id":"call_1","type":"function","function":{"name":"ping","arguments":"{\"value\":\"ok\"}"}}]},
	"finish_reason":"tool_calls"}]}`

// setHome points config.Path() at a fresh, empty directory so each test gets
// its own config file instead of touching the real developer's.
func setHome(t *testing.T) {
	t.Helper()
	home := t.TempDir()
	t.Setenv("HOME", home)
	t.Setenv("USERPROFILE", home)
}

func saveConfig(t *testing.T, c config.Config) {
	t.Helper()
	path, err := config.Path()
	if err != nil {
		t.Fatal(err)
	}
	if err := c.SaveTo(path); err != nil {
		t.Fatal(err)
	}
}

func handlerFor(t *testing.T, fake *fakevllm.Server) http.Handler {
	t.Helper()
	cfg := config.Default()
	cfg.VLLMURL = fake.URL()
	cfg.Model = "m"
	caps, err := probe.Detect(context.Background(), http.DefaultClient, fake.URL(), "")
	if err != nil {
		t.Fatal(err)
	}
	lg, _ := server.NewLogger("off", t.TempDir())
	return server.New(cfg, caps, lg).Handler()
}

func TestSmokeTestPassesWhenModelEmitsAToolCall(t *testing.T) {
	fake := fakevllm.New(fakevllm.Config{
		Models: []string{"m"},
		ChatCompletion: `{"id":"c1","choices":[{"message":{"tool_calls":[
			{"id":"call_1","type":"function","function":{"name":"ping","arguments":"{\"value\":\"ok\"}"}}]},
			"finish_reason":"tool_calls"}]}`,
	})
	defer fake.Close()

	if err := SmokeTest(context.Background(), handlerFor(t, fake), "m"); err != nil {
		t.Fatalf("SmokeTest = %v, want nil", err)
	}
}

func TestSmokeTestFailsWhenModelReturnsProseInsteadOfAToolCall(t *testing.T) {
	fake := fakevllm.New(fakevllm.Config{
		Models: []string{"m"},
		ChatCompletion: `{"id":"c1","choices":[{"message":{"content":
			"Sure! I would call ping with value ok."},"finish_reason":"stop"}]}`,
	})
	defer fake.Close()

	err := SmokeTest(context.Background(), handlerFor(t, fake), "m")
	if err == nil {
		t.Fatal("SmokeTest = nil, want an error naming the missing tool call")
	}
	if !strings.Contains(err.Error(), "tool") {
		t.Errorf("error should mention tool calling, got: %v", err)
	}
}

func TestSmokeTestFailsWhenToolCallHasNoName(t *testing.T) {
	fake := fakevllm.New(fakevllm.Config{
		Models: []string{"m"},
		ChatCompletion: `{"id":"c1","choices":[{"message":{"tool_calls":[
			{"id":"call_1","type":"function","function":{"arguments":"{}"}}]},
			"finish_reason":"tool_calls"}]}`,
	})
	defer fake.Close()

	if err := SmokeTest(context.Background(), handlerFor(t, fake), "m"); err == nil {
		t.Fatal("a nameless tool call should fail the smoke test")
	}
}

// TestSmokeTestFailsWhenToolCallHasNoID exercises the b.ID == "" branch
// directly against a synthetic handler rather than the real bridge: both the
// OpenAI-mode translator (translate.FromOpenAI) and the native passthrough
// path ("Even in passthrough, guarantee tool_use ids." in server.go) repair a
// missing tool_use id before it would ever reach SmokeTest, so routing a
// fakevllm fixture with an empty id through handlerFor cannot exercise this
// branch — the id would already have been generated by the time SmokeTest
// sees the response. Only a handler that hands SmokeTest an already
// Anthropic-shaped response, bypassing that repair, can test it.
func TestSmokeTestFailsWhenToolCallHasNoID(t *testing.T) {
	handler := http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
		w.Header().Set("Content-Type", "application/json")
		io.WriteString(w, `{"id":"msg_1","type":"message","role":"assistant","content":[
			{"type":"tool_use","id":"","name":"ping","input":{"value":"ok"}}]}`)
	})

	err := SmokeTest(context.Background(), handler, "m")
	if err == nil {
		t.Fatal("a tool call with no id should fail the smoke test")
	}
	if !strings.Contains(err.Error(), "id") {
		t.Errorf("error should mention the missing id, got: %v", err)
	}
}

// TestDoctorReportsUnreachableServerAndReturnsErrReported covers finding 1
// and finding 2: Doctor must explain the failure in its own output exactly
// once, and the caller (main) must still see a signal to exit non-zero
// without printing the explanation again.
func TestDoctorReportsUnreachableServerAndReturnsErrReported(t *testing.T) {
	setHome(t)

	c := config.Default()
	// Nothing listens here; dialing localhost on a closed port fails fast
	// with connection refused rather than waiting out a dial timeout.
	c.VLLMURL = "http://127.0.0.1:1"
	c.Model = "m"
	saveConfig(t, c)

	var out bytes.Buffer
	err := Doctor(&out)
	if !errors.Is(err, ErrReported) {
		t.Fatalf("Doctor error = %v, want ErrReported", err)
	}
	got := out.String()
	if !strings.Contains(got, c.VLLMURL) {
		t.Errorf("output does not name the unreachable URL:\n%s", got)
	}
	if !strings.Contains(got, "config set url=") {
		t.Errorf("output does not name the remedy:\n%s", got)
	}
}

// TestDoctorReportsUnservedModelAndReturnsErrReported covers findings 1 and
// 2 for the model-not-served branch.
func TestDoctorReportsUnservedModelAndReturnsErrReported(t *testing.T) {
	fake := fakevllm.New(fakevllm.Config{Models: []string{"served-model"}})
	defer fake.Close()
	setHome(t)

	c := config.Default()
	c.VLLMURL = fake.URL()
	c.Model = "not-served-model"
	saveConfig(t, c)

	var out bytes.Buffer
	err := Doctor(&out)
	if !errors.Is(err, ErrReported) {
		t.Fatalf("Doctor error = %v, want ErrReported", err)
	}
	got := out.String()
	if !strings.Contains(got, "not-served-model") {
		t.Errorf("output does not name the configured model:\n%s", got)
	}
	if !strings.Contains(got, "served-model") {
		t.Errorf("output does not list the models actually served:\n%s", got)
	}
}

// TestDoctorPassesEndToEndAgainstFakeVLLM is the happy path: a reachable
// server, a served model, and a model that emits a well-formed tool call.
func TestDoctorPassesEndToEndAgainstFakeVLLM(t *testing.T) {
	fake := fakevllm.New(fakevllm.Config{
		Models:         []string{"m"},
		ChatCompletion: wellFormedToolCall,
	})
	defer fake.Close()
	setHome(t)

	c := config.Default()
	c.VLLMURL = fake.URL()
	c.Model = "m"
	saveConfig(t, c)

	var out bytes.Buffer
	if err := Doctor(&out); err != nil {
		t.Fatalf("Doctor = %v, want nil\noutput:\n%s", err, out.String())
	}
	if !strings.Contains(out.String(), "PASS") {
		t.Errorf("output does not report the smoke test passing:\n%s", out.String())
	}
}

// TestDoctorNeverPrintsAPIKey is a regression test: the config file can hold
// a real vLLM credential and Doctor's output is meant to be safe to paste
// into a bug report or screen-share.
func TestDoctorNeverPrintsAPIKey(t *testing.T) {
	fake := fakevllm.New(fakevllm.Config{
		Models:         []string{"m"},
		ChatCompletion: wellFormedToolCall,
	})
	defer fake.Close()
	setHome(t)

	const sentinel = "sk-doctor-sentinel-do-not-print"
	c := config.Default()
	c.VLLMURL = fake.URL()
	c.Model = "m"
	c.APIKey = sentinel
	saveConfig(t, c)

	var out bytes.Buffer
	if err := Doctor(&out); err != nil {
		t.Fatalf("Doctor = %v, want nil\noutput:\n%s", err, out.String())
	}
	if strings.Contains(out.String(), sentinel) {
		t.Errorf("Doctor printed the API key:\n%s", out.String())
	}
}

// TestDoctorNoContextWarningWhenServerReportsNoMaxModelLen covers finding 5's
// silent path: printing a warning off a number the server never reported
// would be worse than saying nothing.
func TestDoctorNoContextWarningWhenServerReportsNoMaxModelLen(t *testing.T) {
	fake := fakevllm.New(fakevllm.Config{
		Models:         []string{"m"},
		ChatCompletion: wellFormedToolCall,
		// MaxModelLen left at zero: the fake, like some real vLLM builds,
		// reports no max_model_len at all.
	})
	defer fake.Close()
	setHome(t)

	c := config.Default()
	c.VLLMURL = fake.URL()
	c.Model = "m"
	saveConfig(t, c)

	var out bytes.Buffer
	if err := Doctor(&out); err != nil {
		t.Fatalf("Doctor = %v, want nil\noutput:\n%s", err, out.String())
	}
	if strings.Contains(out.String(), "context_window") {
		t.Errorf("Doctor warned about context_window when the server reported no max_model_len:\n%s", out.String())
	}
}

// TestDoctorWarnsWhenContextWindowExceedsServerMaxModelLen is the positive
// counterpart of the test above: the server did report a max_model_len, and
// it is smaller than the configured context_window, so the warning must
// appear and must name both numbers.
func TestDoctorWarnsWhenContextWindowExceedsServerMaxModelLen(t *testing.T) {
	fake := fakevllm.New(fakevllm.Config{
		Models:         []string{"m"},
		ChatCompletion: wellFormedToolCall,
		MaxModelLen:    32768,
	})
	defer fake.Close()
	setHome(t)

	c := config.Default() // ContextWindow defaults to 131072, well above 32768
	c.VLLMURL = fake.URL()
	c.Model = "m"
	saveConfig(t, c)

	var out bytes.Buffer
	if err := Doctor(&out); err != nil {
		t.Fatalf("Doctor = %v, want nil\noutput:\n%s", err, out.String())
	}
	got := out.String()
	if !strings.Contains(got, "WARN") {
		t.Errorf("output does not warn about the context window mismatch:\n%s", got)
	}
	if !strings.Contains(got, "131072") || !strings.Contains(got, "32768") {
		t.Errorf("output does not name both the configured and server context window:\n%s", got)
	}
}
